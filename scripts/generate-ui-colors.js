// Generates src/uiColors.ts: VS Code's registered UI color IDs with their default values.
//
// VS Code has no API that lists UI colors, so they are read from its bundled workbench code:
//   node scripts/generate-ui-colors.js "<VS Code install>/resources/app/out/vs/workbench/workbench.desktop.main.js"
//
// Defaults that VS Code computes from other colors (darken(...), transparent(...)) are recorded as
// null, like colors without a default.

const fs = require("fs");
const path = require("path");

const file = process.argv[2];
if (!file) {
  console.error("usage: node scripts/generate-ui-colors.js <path to workbench.desktop.main.js>");
  process.exit(1);
}
const src = fs.readFileSync(file, "utf8");

const ID = "[a-zA-Z][\\w-]*(?:\\.[\\w-]+)+";
const hex2 = (n) => Math.round(n).toString(16).padStart(2, "0").toUpperCase();

/** A literal default as #RRGGBB(AA), or null when VS Code derives it at runtime. */
function literal(v) {
  v = v.trim();
  let m = /^"(#[0-9a-fA-F]{3,8})"$/.exec(v);
  if (m) return normalize(m[1]);
  if (/^[\w$]+\.black$/.test(v)) return "#000000";
  if (/^[\w$]+\.white$/.test(v)) return "#FFFFFF";
  if (/^[\w$]+\.transparent$/.test(v)) return "#00000000";
  m = /^new [\w$]+\(new [\w$]+\((\d+),(\d+),(\d+)(?:,([\d.]+))?\)\)$/.exec(v);
  if (m) {
    const a = m[4] === undefined ? 1 : Number(m[4]);
    return `#${hex2(m[1])}${hex2(m[2])}${hex2(m[3])}${a < 1 ? hex2(a * 255) : ""}`;
  }
  return null;
}

function normalize(hex) {
  let h = hex.slice(1).toUpperCase();
  if (h.length <= 4) h = [...h].map((c) => c + c).join("");
  if (h.length === 8 && h.endsWith("FF")) h = h.slice(0, 6);
  return `#${h}`;
}

/** Splits "{dark:a,light:b(c,d),...}" at top-level commas. */
function defaults(obj) {
  const out = { dark: null, light: null, hcDark: null, hcLight: null };
  let depth = 0;
  let start = 1;
  const parts = [];
  for (let i = 1; i < obj.length - 1; i++) {
    const c = obj[i];
    if (c === "(" || c === "[" || c === "{") depth++;
    else if (c === ")" || c === "]" || c === "}") depth--;
    else if (c === "," && depth === 0) {
      parts.push(obj.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(obj.slice(start, obj.length - 1));
  for (const p of parts) {
    const m = /^(dark|light|hcDark|hcLight):([\s\S]*)$/.exec(p.trim());
    if (m) out[m[1]] = literal(m[2]);
  }
  return out;
}

/** The balanced {...} starting at index i. */
function objectAt(i) {
  let depth = 0;
  for (let j = i; j < src.length; j++) {
    if (src[j] === "{") depth++;
    else if (src[j] === "}" && --depth === 0) return src.slice(i, j + 1);
  }
  return "{}";
}

const colors = new Map();

// registerColor("id", defaults, localize(...)), minified to something like de("id",{...},d(123,null))
const register = new RegExp(`\\b[\\w$]{1,3}\\("(${ID})",(null|\\{|"#[0-9a-fA-F]+"|[\\w$.]+,)`, "g");
let m;
while ((m = register.exec(src))) {
  const [, id, start] = m;
  if (colors.has(id)) continue;
  const at = m.index + m[0].length - start.length;
  if (start === "{") {
    const obj = objectAt(at);
    // Only registerColor calls are followed by a localized description.
    if (!/^\{(dark|light|hcDark|hcLight):/.test(obj) || !/^,\s*[\w$]+\(\d+/.test(src.slice(at + obj.length))) continue;
    colors.set(id, defaults(obj));
  } else if (start === "null") {
    if (!/^,\s*[\w$]+\(\d+/.test(src.slice(at + 4))) continue;
    colors.set(id, { dark: null, light: null, hcDark: null, hcLight: null });
  } else if (start.startsWith('"')) {
    if (!/^,\s*[\w$]+\(\d+/.test(src.slice(at + start.length))) continue;
    const v = literal(start);
    colors.set(id, { dark: v, light: v, hcDark: v, hcLight: v });
  }
}

// Terminal ANSI colors are registered from a table: "terminal.ansiRed":{index:1,defaults:{...}}
const ansi = /"(terminal\.ansi\w+)":\{index:\d+,defaults:/g;
while ((m = ansi.exec(src))) {
  if (!colors.has(m[1])) colors.set(m[1], defaults(objectAt(m.index + m[0].length)));
}

const ids = [...colors.keys()].sort();
const q = (v) => (v === null ? "null" : `"${v}"`);
const lines = ids.map((id) => {
  const d = colors.get(id);
  return `  "${id}": [${q(d.dark)}, ${q(d.light)}, ${q(d.hcDark)}, ${q(d.hcLight)}],`;
});

const out = `// Generated by scripts/generate-ui-colors.js from VS Code's workbench code; do not edit.
// UI color ID -> default for [dark, light, hcDark, hcLight]; null when VS Code computes it.

export const UI_COLORS: Record<string, [string | null, string | null, string | null, string | null]> = {
${lines.join("\n")}
};
`;
fs.writeFileSync(path.join(__dirname, "../src/uiColors.ts"), out);
console.log(`${ids.length} UI colors`);
